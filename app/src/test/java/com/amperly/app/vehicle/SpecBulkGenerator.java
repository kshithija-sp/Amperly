package com.amperly.app.vehicle;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * One-time bulk generator for the owned vehicle database.
 *
 * <p>Reads {@code tools/vehicle_candidates.json}, checks each candidate against the owned spec
 * database, estimates the ones that are missing, and writes a proposal plus a review sheet. It
 * never edits the shipped database directly: every generated entry is LOW confidence and is
 * listed with the reason it needs a human check, so a bad inference cannot silently become
 * "verified".
 *
 * <p>Run with {@code ./gradlew :app:generateVehicleSpecs}. The class lives in the test source set
 * so it is not shipped in the APK.
 */
public final class SpecBulkGenerator {

    private SpecBulkGenerator() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length < 3) {
            System.err.println("usage: SpecBulkGenerator <candidates.json> <vehicle_specs.json> <outDir>");
            System.exit(2);
        }
        File candidatesFile = new File(args[0]);
        File specsFile = new File(args[1]);
        File outDir = new File(args[2]);

        VehicleSpecDatabase database = VehicleSpecDatabase.fromJson(read(specsFile));
        List<Candidate> candidates = readCandidates(candidatesFile);
        List<Generated> generated = generate(candidates, database);

        if (!outDir.exists() && !outDir.mkdirs()) {
            throw new IOException("cannot create " + outDir);
        }
        write(outDir, generated);
        int covered = coveredCount(generated);
        System.out.println("Candidates: " + candidates.size()
                + " | covered: " + covered
                + " | generated: " + (generated.size() - covered));
        System.out.println("Review sheet: " + new File(outDir, "REVIEW.md").getAbsolutePath());
    }

    /** Pure generation step, exposed for tests. */
    public static List<Generated> generate(List<Candidate> candidates, VehicleSpecDatabase database) {
        List<Generated> generated = new ArrayList<>();
        for (Candidate candidate : candidates) {
            VehicleSpecs existing = database.find(candidate.make, candidate.model, candidate.variant);
            if (existing != null) {
                generated.add(new Generated(candidate, existing, true, "already in owned database"));
                continue;
            }
            VehicleSpecs estimate = SpecEstimator.estimate(candidate.make, candidate.model,
                    candidate.variant);
            List<String> flags = new ArrayList<>();
            flags.add("dimensions estimated from the "
                    + estimate.bodyType.getLabel().toLowerCase(Locale.US) + " template");
            flags.add("confirm body type with the eight-silhouette picker");
            if (estimate.lengthMm <= 0 || estimate.widthMm <= 0 || estimate.heightMm <= 0) {
                flags.add("missing dimensions");
            }
            if (estimate.wheelbaseMm <= 0) {
                flags.add("missing wheelbase");
            }
            generated.add(new Generated(candidate, estimate, false, String.join("; ", flags)));
        }
        return generated;
    }

    private static int coveredCount(List<Generated> generated) {
        int covered = 0;
        for (Generated entry : generated) {
            if (entry.covered) {
                covered++;
            }
        }
        return covered;
    }

    private static void write(File outDir, List<Generated> generated) throws IOException {
        JsonObject document = new JsonObject();
        document.addProperty("schemaVersion", 1);
        document.addProperty("units", "millimetres");
        document.addProperty("notes", "Generated proposal. LOW confidence until reviewed against "
                + "a manufacturer sheet. Review REVIEW.md before promoting an entry.");
        JsonArray vehicles = new JsonArray();
        for (Generated entry : generated) {
            if (entry.covered) {
                continue;
            }
            vehicles.add(toJson(entry.specs));
        }
        document.add("vehicles", vehicles);
        Files.write(new File(outDir, "vehicle_specs.generated.json").toPath(),
                new Gson().toJson(document).getBytes(StandardCharsets.UTF_8));

        StringBuilder review = new StringBuilder();
        review.append("# Vehicle spec review\n\n");
        review.append("Generated by `SpecBulkGenerator`. **Do not promote an entry until its "
                + "dimensions and body type have been checked against a manufacturer sheet.**\n\n");
        review.append("| Make | Model | Variant | Body | L×W×H (mm) | Wheelbase | Status |\n");
        review.append("| --- | --- | --- | --- | --- | --- | --- |\n");
        for (Generated entry : generated) {
            VehicleSpecs specs = entry.specs;
            review.append("| ").append(escape(specs.make))
                    .append(" | ").append(escape(specs.model))
                    .append(" | ").append(escape(specs.variant))
                    .append(" | ").append(specs.bodyType.getLabel())
                    .append(" | ").append(specs.lengthMm).append("×")
                    .append(specs.widthMm).append("×").append(specs.heightMm)
                    .append(" | ").append(specs.wheelbaseMm)
                    .append(" | ");
            if (entry.covered) {
                review.append("covered (").append(entry.notes).append(")");
            } else {
                review.append("REVIEW: ").append(entry.notes);
            }
            review.append(" |\n");
        }
        Files.write(new File(outDir, "REVIEW.md").toPath(),
                review.toString().getBytes(StandardCharsets.UTF_8));
    }

    private static JsonObject toJson(VehicleSpecs specs) {
        JsonObject object = new JsonObject();
        object.addProperty("make", specs.make);
        object.addProperty("model", specs.model);
        if (specs.variant != null && !specs.variant.isEmpty()) {
            object.addProperty("variant", specs.variant);
        }
        object.addProperty("bodyType", specs.bodyType.name());
        object.addProperty("lengthMm", specs.lengthMm);
        object.addProperty("widthMm", specs.widthMm);
        object.addProperty("heightMm", specs.heightMm);
        object.addProperty("wheelbaseMm", specs.wheelbaseMm);
        object.addProperty("groundClearanceMm", specs.groundClearanceMm);
        JsonObject tyre = new JsonObject();
        tyre.addProperty("widthMm", specs.tyreWidthMm);
        tyre.addProperty("aspectPercent", specs.tyreAspectPercent);
        tyre.addProperty("rimDiameterIn", specs.rimDiameterIn);
        object.add("tyre", tyre);
        object.addProperty("chargePort", specs.chargePort.name());
        object.addProperty("source", "generated");
        object.addProperty("confidence", "LOW");
        return object;
    }

    private static List<Candidate> readCandidates(File file) throws IOException {
        Document document = new Gson().fromJson(read(file), Document.class);
        if (document == null || document.candidates == null) {
            return new ArrayList<>();
        }
        return document.candidates;
    }

    private static String read(File file) throws IOException {
        return new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8);
    }

    private static String escape(String value) {
        return value == null ? "" : value.replace("|", "\\|");
    }

    public static final class Candidate {
        public String make;
        public String model;
        public String variant;
    }

    private static final class Document {
        List<Candidate> candidates;
    }

    /** One generated row and whether it was already covered by the owned database. */
    public static final class Generated {
        public final Candidate candidate;
        public final VehicleSpecs specs;
        public final boolean covered;
        public final String notes;

        Generated(Candidate candidate, VehicleSpecs specs, boolean covered, String notes) {
            this.candidate = candidate;
            this.specs = specs;
            this.covered = covered;
            this.notes = notes;
        }
    }
}
